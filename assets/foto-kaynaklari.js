/** assets/img/<kök>-NNN.webp adresinin atıf kaydı (yoksa null). */
export function fotoKaynagi(url) {
  const m = /^assets\/img\/([a-z0-9-]+?)-\d+\.webp$/.exec(String(url || ''));
  return (m && FOTO_KAYNAKLARI[m[1]]) || null;
}
